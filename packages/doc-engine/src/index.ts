function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function renderMarkdown(summary: RunSummary, language: 'id' | 'en'): string {
  const labels = LABELS[language];
  const lines: string[] = [
    `# ${labels.title} — ${summary.run.id}`,
    '',
    `- ${labels.status}: **${summary.run.status}**`,
    `- ${labels.gate}: **${summary.gate.decision}**`,
    `- ${labels.mode}: ${summary.run.mode}`,
    `- ${labels.scope}: ${summary.run.scope}`,
    `- ${labels.time}: ${summary.run.startedAt} → ${summary.run.finishedAt} (${summary.run.durationMs} ms)`,
    '',
    `## ${labels.gate}`,
    '',
  ];

  if (summary.gate.reasons.length === 0) {
    lines.push('- —');
  } else {
    for (const reason of summary.gate.reasons) lines.push(`- ${reason}`);
  }

  lines.push(
    '',
    `## ${labels.stages}`,
    '',
    `| ${labels.stage} | ${labels.stageStatus} | ${labels.duration} | ${labels.reason} |`,
    '|---|---|---:|---|',
  );
  for (const stage of Object.values(summary.stages)) {
    const reason = stage.reason ?? stage.error ?? '';
    lines.push(
      `| ${stage.name} | ${stage.status} | ${stage.durationMs} ms | ${reason.replace(/\|/g, '\\|')} |`,
    );
  }

  if (summary.lanes && summary.lanes.length > 0) {
    lines.push(
      '',
      `## ${labels.lanes}`,
      '',
      `| ${labels.lane} | Status | ${labels.tests} | ${labels.passed} | ${labels.failed} | ${labels.skipped} | ${labels.reason} |`,
      '|---|---|---:|---:|---:|---:|---|',
    );
    for (const lane of summary.lanes) {
      lines.push(
        `| ${lane.lane} | ${lane.status} | ${lane.tests} | ${lane.passed} | ${lane.failed} | ${lane.skipped} | ${(lane.reason ?? '').replace(/\|/g, '\\|')} |`,
      );
    }
  }

  if (summary.appMap) {
    lines.push(
      '',
      `## ${labels.appMap}`,
      '',
      `- ${labels.pages}: ${summary.appMap.pages}`,
      `- ${labels.endpoints}: ${summary.appMap.endpoints}`,
      `- ${labels.codeRefs}: ${summary.appMap.code}`,
      `- ${labels.edges}: ${summary.appMap.edges}`,
      `- ${labels.highRisk}: ${summary.appMap.highRisk}`,
      `- ${labels.changed}: ${summary.appMap.changed}`,
      `- JSON: \`${summary.appMap.path}\``,
    );
  }

  lines.push('', `## ${labels.findings}`, '');
  if (summary.findings.length === 0) {
    lines.push(labels.noFindings);
  } else {
    lines.push(
      `| ID | ${labels.severity} | ${labels.confidence} | ${labels.finding} | ${labels.lanes} |`,
      '|---|---|---|---|---|',
    );
    for (const finding of summary.findings) {
      lines.push(
        `| ${finding.id} | ${finding.severity} | ${finding.confidence} | ${finding.title.replace(/\|/g, '\\|')} | ${finding.lanes.join(', ')} |`,
      );
    }
  }
  lines.push('', `## ${labels.limitations}`, '');
  if (summary.limitations.length === 0) {
    lines.push('- —');
  } else {
    for (const limitation of summary.limitations) lines.push(`- ${limitation}`);
  }

  lines.push('', `## ${labels.audit}`, '');
  lines.push(`- ${labels.run}: ${summary.audit.runId}`);
  lines.push(`- ${labels.name}: ${summary.audit.requestedBy}`);
  lines.push(`- ${labels.started}: ${summary.audit.startedAt}`);
  lines.push(`- ${labels.finished}: ${summary.audit.finishedAt ?? '—'}`);
  lines.push(
    '',
    `## ${labels.request}`,
    '',
    '```json',
    JSON.stringify(summary.request, null, 2),
    '```',
  );
  lines.push('', `_${labels.generated}_`, '');
  return lines.join('\n');
}

